// Натан любит велосипед.
// Поскольку Натан знает, что важно пить водный баланс, он пьёт 0,5 литра воды в час цикла.
// Вам указывают время в часах, и вам нужно вернуть количество литров, которые Натан выпьет, округленное вниз.

// Например:

// time = 3 ----> litres = 1
// time = 6.7---> litres = 3
// time = 11.8--> litres = 5

function litres(time) {
  const litres = time * 0.5;
  const remainder = litres % 1;
  const result = litres - remainder;
  return result;
}

// Задача 5
// Заполните функцию квадратной суммы так, чтобы она поставила каждое число, прошедшее в неё, и затем суммировали результаты вместе.

// Например, для он должен возвращаться, потому что [1, 2, 2]9
// 1**2+2**2+2**2=9

function squareSum(numbers) {
  let sum = 0;
  numbers.forEach((num) => {
    sum = num ** 2 + sum;
  });
  return sum;
}

// Задача 6
// Создайте функцию, которая принимает целое число в качестве аргумента и возвращает "Even" для чётных чисел или "Odd" для нечётных чисел.

function evenOrOdd(number) {
  if (number % 2 === 0 && number % 1 === 0) {
    return "Even";
  } else if (number % 2 !== 0 && number % 1 === 0) {
    return "Odd";
  }
}
